"""Generate a standalone bundle: python -m starter.generate --config ... --output ..."""
import argparse
import json
from pathlib import Path
import shutil
import yaml
from .config import read

ROOT = Path(__file__).resolve().parents[1]


def generate(c, output):
    output = Path(output).resolve()
    if output.exists():
        raise ValueError('Output already exists; choose a new directory to preserve local work')
    output.mkdir(parents=True)
    shutil.copy2(ROOT/'LICENSE', output/'LICENSE')
    (output/'project.json').write_text(json.dumps(c, indent=2), encoding='utf-8')
    for folder in ('agents', 'app'):
        shutil.copytree(ROOT/'src'/folder, output/'src'/folder, ignore=shutil.ignore_patterns('__pycache__'))
    # Local-source Apps avoid coupling generated projects to the author's Git repository.
    app = output/'src/app/app.py'
    source = app.read_text(encoding='utf-8')
    start = source.index('demo = gr.ChatInterface(')
    end = source.index('\nif __name__', start)
    source = source[:start] + ('demo = gr.ChatInterface(fn=respond, title=' + repr(c['name']) + ', description=' + repr(c['description'] + ' Enabled workflows: ' + ', '.join(c['agents']) + '. ETL outputs are temporary.') + ', examples=' + repr([x['question'] for x in c['checks']]) + ')\n') + source[end:]
    app.write_text(source, encoding='utf-8')
    shutil.copytree(ROOT/'starter/templates', output/'notebooks', ignore=shutil.ignore_patterns('__pycache__'))
    for path in (output/'notebooks').glob('*.py'):
        path.write_text(path.read_text(encoding='utf-8').replace('PROJECT_CONFIG_LITERAL', repr(c)), encoding='utf-8')
    shutil.copy2(ROOT/'starter/verify.py', output/'verify.py')
    variables = {'app_name': {'default': c['name']+'-${workspace.current_user.domain_friendly_name}'},
                 'endpoint_name': {'default': c['name']+'-endpoint'}}
    tasks = []
    for key, file in [('prepare_data','prepare.py'), ('create_tools','tools.py'), ('deploy_agent','deploy.py')]:
        task = {'task_key': key, 'notebook_task': {'notebook_path': './notebooks/'+file, 'base_parameters': {
            'agent_source': '${workspace.file_path}/src/agents/agent.py', 'endpoint_name': '${var.endpoint_name}'}}}
        if tasks:
            task['depends_on'] = [{'task_key': tasks[-1]['task_key']}]
        tasks.append(task)
    app_resource = {'apps': {'agent_app': {'name': '${var.app_name}', 'source_code_path': './src/app',
                     'resources': [{'name': 'agent-endpoint', 'serving_endpoint': {'name': '${var.endpoint_name}', 'permission': 'CAN_QUERY'}}]}}}
    bundle = {'bundle': {'name': c['name']}, 'variables': variables,
              'resources': {'jobs': {'setup': {'name': c['name']+'-setup', 'tags': {'aidevkit_project': c['name']}, 'tasks': tasks}}},
              'targets': {'dev': {'default': True, 'mode': 'development', 'workspace': {'host': c['host'], 'profile': c['profile']}}}}
    (output/'databricks.yml').write_text(yaml.safe_dump(bundle, sort_keys=False), encoding='utf-8')
    (output/'app.resource.yml').write_text(yaml.safe_dump(app_resource, sort_keys=False), encoding='utf-8')
    (output/'enable_app.py').write_text("from pathlib import Path\nimport yaml\np=Path(__file__).resolve().parent\nb=yaml.safe_load((p/'databricks.yml').read_text())\nb['resources'].update(yaml.safe_load((p/'app.resource.yml').read_text()))\n(p/'databricks.yml').write_text(yaml.safe_dump(b,sort_keys=False))\nprint('App added; validate and deploy the bundle again.')\n",encoding='utf-8')
    (output/'src/app/app.yaml').write_text(yaml.safe_dump({'command': ['python','app.py'], 'env': [{'name': 'SERVING_ENDPOINT', 'valueFrom': 'agent-endpoint'}]}),encoding='utf-8')
    (output/'.gitignore').write_text('.databricks/\n.venv/\n__pycache__/\nverification.json\n',encoding='utf-8')
    (output/'requirements.txt').write_text('databricks-sdk==0.146.0\ngradio-client==2.7.2\nPyYAML==6.0.3\n',encoding='utf-8')
    (output/'AGENTS.md').write_text('Use Databricks core, DAB, jobs and serverless skills. Validate the bundle before deployment. Never overwrite existing input tables. project.json is non-secret configuration.\n',encoding='utf-8')
    (output/'README.md').write_text(f'# {c["name"]}\n\nGenerated by Multi-Agent Starter Kit v0.1.0.\n\nFollow https://pratik2895.github.io/ai-data-agent/quickstart.html .\nConfiguration is baked into notebooks; regenerate in a new directory after changes.\n',encoding='utf-8')
    return output


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--config', required=True)
    p.add_argument('--output', required=True)
    args=p.parse_args()
    print(generate(read(args.config), args.output))

if __name__ == '__main__':
    main()
